/**
 * El arranque solo siembra si no hay marcas. completar:true permite agregar
 * marcas y asociaciones faltantes sin borrar ni cambiar las existentes.
 * Corre después de las familias, dentro de la misma transaction al actualizar.
 */
export async function seed_marcas_distribuidora({ completar = false, transaction } = {}) {
  if (!projectModules.eccomerce_distribuidora) return;
  if (!completar && await MarcaDistribuidora.count({ transaction })) return;
  const modelos = { CategoriaDistribuidora, MarcaDistribuidora, MarcaCategoriaDistribuidora };
  const ejecutar = (tx) => completarMarcas(modelos, MARCAS_INICIALES, tx);
  if (transaction) return ejecutar(transaction);
  const resultado = await sequelize.transaction(ejecutar);
  if (resultado.faltantes.length) console.warn(`⚠️ Marcas: rutas omitidas ${resultado.faltantes.join(", ")}`);
  console.log(`✅ Marcas: ${resultado.marcas} marcas y ${resultado.asociaciones} asociaciones agregadas`);
  return resultado;
}
